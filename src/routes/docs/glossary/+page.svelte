<dl>
	<dt>Abstain</dt>
	<dd>
		Taking part in a vote without taking a side. Counts toward the quorum, not for or against.
	</dd>

	<dt>Activity marker</dt>
	<dd>
		A record of a featured app's activity, made in the same transaction. Where the network rewards
		apps by marker, it lowers what that transaction is charged.
	</dd>

	<dt>Address</dt>
	<dd>
		Where you send Canton Coin to top up a balance: the party of the app's validator, shown under
		Top up.
	</dd>

	<dt>App, the</dt>
	<dd>
		SyncVotes as it runs on a network: the site, its server, and the provider party that co-signs
		every contract.
	</dd>

	<dt>App rewards</dt>
	<dd>
		Canton Coin the network mints for a featured app's activity. SyncVotes subtracts them from the
		price where it earns them.
	</dd>

	<dt>Balance</dt>
	<dd>
		What is left to spend on traffic: topped up less spent. Your own on the Wallet page, a DAO's on
		its page.
	</dd>

	<dt>Ballot</dt>
	<dd>One member's vote on one proposal, signed with their key and weighing their units.</dd>

	<dt>Basis</dt>
	<dd>What yes is measured against: the whole vote, or the votes cast (yes and no only).</dd>

	<dt>Canton Coin (CC)</dt>
	<dd>The Canton Network's native coin. It pays for traffic.</dd>

	<dt>Changes to the DAO</dt>
	<dd>
		Proposals that change the DAO: Members or Shares, Name and description, Voting rules, Visibility
		and Dissolve. They run under the DAO's voting rules.
	</dd>

	<dt>Choice</dt>
	<dd>A proposal where members pick from 2 to 10 options, one each or several.</dd>

	<dt>Counting</dt>
	<dd>
		The status of a proposal whose deadline has passed and whose last ballots are being counted.
	</dd>

	<dt>Create</dt>
	<dd>What you do to start a DAO. Its creator has no powers beyond those of any member.</dd>

	<dt>DAO</dt>
	<dd>
		A group that decides by vote, as contracts on the ledger. It votes by membership or by shares.
	</dd>

	<dt>DAO ID</dt>
	<dd>
		A DAO's permanent identifier, in its page's address. Use it to check a DAO is the real one.
	</dd>

	<dt>Decided</dt>
	<dd>The status of a choice that picked one or more options.</dd>

	<dt>Decision</dt>
	<dd>A yes-or-no proposal that records the DAO's position and changes nothing else.</dd>

	<dt>Decisions and choices</dt>
	<dd>Proposals that change nothing on the ledger. They run under the proposer's rule.</dd>

	<dt>Display name</dt>
	<dd>
		The name in your profile, shown next to your party ID. It can change; the party ID cannot.
	</dd>

	<dt>Dissolve</dt>
	<dd>To close a DAO permanently, by a proposal that passes under its voting rules.</dd>

	<dt>Electorate</dt>
	<dd>The members and units of a DAO at the moment a proposal is made: who votes on it.</dd>

	<dt>Executed</dt>
	<dd>The status of a change to the DAO that passed and is now in effect on the ledger.</dd>

	<dt>External party</dt>
	<dd>
		A party whose signing key is held outside the ledger, by its owner. Every SyncVotes party is
		one.
	</dd>

	<dt>Failed</dt>
	<dd>
		The status of a proposal that did not meet its rule, missed its quorum, or ended in a tie.
	</dd>

	<dt>Featured app</dt>
	<dd>An app the Canton Network recognizes for rewards on the activity it brings.</dd>

	<dt>Fingerprint</dt>
	<dd>The hash of your public key that forms the second half of your party ID.</dd>

	<dt>Invite code</dt>
	<dd>A code the app asks for before it creates a party, while sign-up is by invitation.</dd>

	<dt>Key</dt>
	<dd>Your signing key, made from your recovery phrase and kept in your browser.</dd>

	<dt>Lock</dt>
	<dd>To remove the key from the page's memory. The encrypted copy stays on the device.</dd>

	<dt>Member</dt>
	<dd>A party that holds units in a DAO and can propose, vote and comment in it.</dd>

	<dt>Memo</dt>
	<dd>
		The text a top-up must carry to be credited: <code>syncvotes:</code> and the balance's ID.
	</dd>

	<dt>Not voted</dt>
	<dd>Open proposals you can vote on and have not yet.</dd>

	<dt>Open</dt>
	<dd>The status of a proposal whose vote is open.</dd>

	<dt>Party</dt>
	<dd>Your identity on the Canton ledger. Contracts name parties, and transactions act as them.</dd>

	<dt>Party hint</dt>
	<dd>The first half of a party ID, chosen when the party is created.</dd>

	<dt>Party ID</dt>
	<dd>A party's full name on the ledger: the party hint, two colons and the fingerprint.</dd>

	<dt>Passed</dt>
	<dd>The status of a proposal that met its rule. A change shows Executed once it is in effect.</dd>

	<dt>Passkey</dt>
	<dd>A device credential (fingerprint, face or PIN) that can unlock a key kept on the device.</dd>

	<dt>Preset</dt>
	<dd>A named combination of basis, threshold and quorum, such as Two thirds of the vote.</dd>

	<dt>Profile</dt>
	<dd>An optional display name, picture and About text for your party.</dd>

	<dt>Proposal</dt>
	<dd>A question put to a DAO's members, with a rule, a deadline and an effect if it passes.</dd>

	<dt>Proposer's rule</dt>
	<dd>The rule the proposer sets for a decision or a choice.</dd>

	<dt>Provider party</dt>
	<dd>The app's own party. It co-signs every contract, counts ballots and executes what passed.</dd>

	<dt>Quorum</dt>
	<dd>The share of the whole vote that must take part for a proposal to pass.</dd>

	<dt>Reader</dt>
	<dd>Someone signed in who reads a public DAO without being a member.</dd>

	<dt>Recovery phrase</dt>
	<dd>The 12 words your key is made from. The only way to restore it.</dd>

	<dt>Scan</dt>
	<dd>
		The Canton Network's public service for Canton Coin data, where the app reads prices and
		rewards.
	</dd>

	<dt>Secret ballot</dt>
	<dd>
		A ballot where members see the totals and only their own vote. The app still sees every ballot.
	</dd>

	<dt>Settle early</dt>
	<dd>
		A rule setting that decides a proposal as soon as the remaining votes cannot change the outcome.
	</dd>

	<dt>Sign in</dt>
	<dd>To create, restore or unlock a key, so that the app can read and act as your party.</dd>

	<dt>Spent</dt>
	<dd>What a balance's transactions have cost so far.</dd>

	<dt>Threshold</dt>
	<dd>How much of the basis yes must reach: more than half, a fraction, or a percentage.</dd>

	<dt>Top up</dt>
	<dd>To add Canton Coin to a balance by sending it to the Address with the Memo.</dd>

	<dt>Topped up</dt>
	<dd>Everything credited to a balance so far.</dd>

	<dt>Traffic</dt>
	<dd>Canton's term for transaction fees, charged by the size of each transaction.</dd>

	<dt>Units</dt>
	<dd>
		Whole numbers of the vote a member holds: 1 each in a DAO by membership, any number by shares.
	</dd>

	<dt>Validator</dt>
	<dd>A Canton node that hosts parties. The app's validator hosts every SyncVotes party.</dd>

	<dt>Votes cast</dt>
	<dd>A basis that counts only yes and no, leaving out members who abstain or do not vote.</dd>

	<dt>Votes may change</dt>
	<dd>
		A rule setting that lets members vote again until the deadline. It excludes settling early.
	</dd>

	<dt>Voting period</dt>
	<dd>How long a vote is open, 1 to 90 days from the moment the proposal is signed.</dd>

	<dt>Voting power</dt>
	<dd>A member's units as a percentage of the DAO's total.</dd>

	<dt>Voting rules</dt>
	<dd>The DAO's rule and voting period for every change to the DAO.</dd>

	<dt>Wallet</dt>
	<dd>The page where you create, restore, unlock and lock your key, and see your balance.</dd>

	<dt>Whole vote</dt>
	<dd>Every unit of the DAO when the proposal was made. As a basis, silence counts as no.</dd>
</dl>
